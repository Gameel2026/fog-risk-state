"""Embedded step 1b (exploratory, PLAN section 8): deployable model for 16-Hz sampling and its C header.
Same procedure as p4_deploy_model.py on the 16-Hz variant (gait gate: same label-free Otsu rule recomputed for this rate).
The model is trained once on all gated 16-Hz windows of both datasets
(same features, patient weights, C = 1, median imputation and standardisation as in p3_analysis.py).
Outputs: results/deploy_model_fs16.json and mcu16/fog_params.h
"""
import os
import json
import numpy as np
import pandas as pd
import p_config as C
import p3_analysis as P

FS = C.VARIANTS["fs16"]["fs"]
N = int(round(C.WIN_S * FS))


def main():
    R = pd.read_csv(os.path.join(C.OUT, "recordings.csv"), dtype={"subject": str})
    gate = json.load(open(os.path.join(C.OUT, "frozen_gate.json")))
    W, ginfo = P.load_variant("fs16", gate, R)
    a = P.arrays(W, C.FEATURES)
    prep = P.Prep(a["X"])
    w = P.fit_lr(prep(a["X"]), a["y"].astype(float), P.patient_weights(a["pid"]))
    model = {"features": C.FEATURES, "median": prep.med.tolist(), "mean": prep.mu.tolist(), "sd": prep.sd.tolist(),
             "coef": w[:-1].tolist(), "intercept": float(w[-1]),
             "gate_logP_loc": ginfo["threshold"], "gate_rule": ginfo["rule"], "gate_ac": gate["ac_threshold"],
             "fs": FS, "window_samples": N, "n_windows_trained": int(len(W))}
    json.dump(model, open(os.path.join(C.OUT, "deploy_model_fs16.json"), "w"), indent=2)

    # tables reproducing numpy exactly
    f = np.fft.rfftfreq(N, 1.0 / FS)
    loc = np.flatnonzero((f >= 0.5) & (f < 3.0))
    frz = np.flatnonzero((f >= 3.0) & (f <= min(8.0, FS / 2 - 1e-9)))
    assert frz[0] == loc[-1] + 1
    hr = np.full((loc[-1] + 1, 10), -1, int)
    for k in loc:
        fst = f[k] / 2.0
        for j in range(1, 11):
            fk = j * fst
            if fk >= FS / 2:
                break
            hr[k, j - 1] = int(np.argmin(np.abs(f - fk)))
    lo, hi = int(0.3 * FS), min(int(1.2 * FS), N - 1)
    l2lo = np.zeros(hi, int)
    l2hi = np.zeros(hi, int)
    for lag in range(lo, hi):
        l2lo[lag], l2hi[lag] = int(1.6 * lag), min(int(2.4 * lag) + 1, N - 1)
    ac_max = int(max(l2hi.max() - 1, hi - 1))

    def arr(name, v, ctype="float", fmt="%.9e"):
        body = ", ".join((fmt % x) + ("f" if ctype == "float" else "") for x in v)
        return "static const %s %s[%d] = { %s };\n" % (ctype, name, len(v), body)

    h = ["/* generated by p4_deploy_model.py - do not edit */\n#ifndef FOG_PARAMS_H\n#define FOG_PARAMS_H\n",
         "#define NFEAT %d\n#define K_LOC0 %d\n#define K_LOC1 %d\n#define K_FRZ1 %d\n" % (len(C.FEATURES), loc[0], loc[-1], frz[-1]),
         "#define AC_LO %d\n#define AC_HI %d\n#define AC_MAX %d\n" % (lo, hi, ac_max),
         "#define GATE_LOGP %.9ef\n#define GATE_AC %.9ef\n#define W_B %.9ef\n" % (ginfo["threshold"], gate["ac_threshold"], w[-1]),
         arr("HANN", np.hanning(N)), arr("COS_T", np.cos(2 * np.pi * np.arange(N) / N)),
         arr("W_MED", prep.med), arr("W_MU", prep.mu), arr("W_SD", prep.sd), arr("W_COEF", w[:-1]),
         arr("L2LO", l2lo, "int16_t", "%d"), arr("L2HI", l2hi, "int16_t", "%d"),
         "static const int16_t HR_IDX[%d][10] = {\n" % hr.shape[0]
         + ",\n".join("  { " + ", ".join(str(v) for v in row) + " }" for row in hr) + "\n};\n",
         "#endif\n"]
    open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "mcu16", "fog_params.h"), "w").write("".join(h))
    print("wrote results/deploy_model_fs16.json and mcu16/fog_params.h; trained on", len(W), "windows")


if __name__ == "__main__":
    main()
